    private void preencherTabela(ArrayList<Pessoa> lista) {
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tabela_de_pessoas.getModel();
        
        // Zera as linhas da tabela
        modelo.setNumRows(0); 

        // Preenche com a lista que foi passada
        for (Pessoa p : lista) {
            modelo.addRow(new Object[]{
                p.getId(),
                p.getNome(),
                p.getIdade()
            });
        }
    }
    
    private void listarPessoas() {
        ArrayList<Pessoa> lista_pessoa = Pessoa_Controle.lista_de_pessoa();
        preencherTabela(lista_pessoa);
    }

