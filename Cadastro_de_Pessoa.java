    private void button_removerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_button_removerActionPerformed
        // TODO add your handling code here:
        try {
            String idStr = javax.swing.JOptionPane.showInputDialog(this, "Digite o ID que deseja remover : ");
            if (idStr != null && !idStr.isEmpty()){
                int id = Integer.parseInt(idStr);
                Pessoa_Controle.remover(id);
                javax.swing.JOptionPane.showMessageDialog(this, "Pessoa removida com sucesso!");
                
                listarPessoas();
            }
        } catch (NumberFormatException e){
            javax.swing.JOptionPane.showMessageDialog(this, "ID inválido");
        }
    }//GEN-LAST:event_button_removerActionPerformed

    private void button_atualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_button_atualizarActionPerformed
        // TODO add your handling code here:
        
        String nome = txt_nome.getText().trim();
        String idadeStr = txt_idade.getText().trim();
        
        if (nome.isEmpty() || idadeStr.isEmpty()){
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, Digite um novo nome e uma idade!");
            return;
        }
        
        try{
            
            int idade = Integer.parseInt(idadeStr);
            String idStr = javax.swing.JOptionPane.showInputDialog(this, "Digite o ID da pessoa que deseja atualizar: ");
            if (idStr != null && !idStr.trim().isEmpty()){
                int id = Integer.parseInt(idStr.trim());
                
                Pessoa_Controle.atualizar(id, nome, idade);
                javax.swing.JOptionPane.showMessageDialog(this, "Dados atualizados com sucesso!");
                
                txt_nome.setText("");
                txt_idade.setText("");
                
                listarPessoas();
            }
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro nos dados informados!!");
        }
        
    }//GEN-LAST:event_button_atualizarActionPerformed

